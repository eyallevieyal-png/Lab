"""Build research/EXPERIMENT_REGISTRY.json: one entry per experiment, with evidence class, provenance and a content hash of every output.

    python -m research.registry.build_registry

Evidence classes (README.md explains them):
  reproduced              re-run in the 2026-11-28 audit and the committed output was byte-identical
  validated_simulation    simulator output; the simulator passed the 8 executable defect checks and the test suite. Simulated, NOT measured.
  preliminary_hardware    real timings, but one machine / one run: not a hardware specification
  theoretical             derivation or calculation from specs; proofs hold inside the stated model only
  superseded              produced by obsolete code, archived, not valid for conclusions
  unverified_hypothesis   designed, not run
`class` is the strongest claim the evidence supports; `also` lists secondary labels (for example a re-run script whose output is a simulation).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = "experiments/results/"


def sha(path: str) -> str | None:
    p = os.path.join(ROOT, path)
    return hashlib.sha256(open(p, "rb").read()).hexdigest() if os.path.exists(p) else None


def e(id_, title, hypothesis, cls, script, outputs, *, seeds=None, runs=None, validation, notes="", also=()):
    reproduce = None
    if script:
        reproduce = script if script.startswith("python") else f"python -X utf8 {script}"
    return {
        "id": id_, "title": title, "hypothesis": hypothesis, "class": cls, "also": list(also), "script": script,
        "outputs": [{"path": o, "sha256": sha(o), "exists": sha(o) is not None} for o in outputs],
        "seeds": seeds, "runs": runs, "validation_status": validation, "reproduce": reproduce, "notes": notes,
    }


