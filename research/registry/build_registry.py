def main() -> None:
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    counts: dict = {}
    for x in REGISTRY:
        counts[x["class"]] = counts.get(x["class"], 0) + 1
    out = {"generated_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "repo_head_when_generated": commit,
           "classes": counts, "experiments": REGISTRY}
    with open(os.path.join(ROOT, "research", "EXPERIMENT_REGISTRY.json"), "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2, ensure_ascii=False)
    print("classes:", counts)
    print("outputs not present yet:", [o["path"] for x in REGISTRY for o in x["outputs"] if not o["exists"]])


if __name__ == "__main__":
    main()
